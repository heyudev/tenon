/** 主词条与别名统一建索引 */
const INDEX: { key: string; term: Term }[] = GLOSSARY.flatMap((t) => [
  { key: t.t, term: t },
  ...(t.alias ?? []).map((a) => ({ key: a, term: t })),
]).sort((a, b) => b.key.length - a.key.length) // 长词优先，避免"章级"吃掉"章级卷级书级"

/** 扫一段文字，返回里面出现过的术语（去重、按出现顺序） */
export function termsIn(...texts: (string | string[] | undefined)[]): Term[] {
  const blob = texts
    .flatMap((t) => (Array.isArray(t) ? t : [t ?? '']))
    .join('\n')
  const hit = new Map<string, Term>()
  for (const { key, term } of INDEX) {
    if (blob.includes(key)) hit.set(term.t, term)
  }
  return [...hit.values()]
}

export function lookup(key: string): Term | undefined {
  return INDEX.find((x) => x.key === key)?.term
}
